// Generates schemas-strict/README.md from schemas-strict/mapping-manifest.json (+ the stage map).
// Usage: node tools/belt/build-readme.mjs    (run build-mapping-manifest.mjs first)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { sha256File } from './lib/hash.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(here, '..', '..');
const manifest = JSON.parse(readFileSync(join(ROOT, 'schemas-strict/mapping-manifest.json'), 'utf8'));
const stageMap = JSON.parse(readFileSync(join(ROOT, 'schemas-strict/stage-map.json'), 'utf8'));

const L = [];
L.push('# schemas-strict — pilot adapters for the v0.4.0 Meta lane (Claude lane)');
L.push('');
L.push('Generated by `tools/belt/build-readme.mjs` from `mapping-manifest.json` ' + `(sha256 \`${sha256File(join(ROOT, 'schemas-strict/mapping-manifest.json'))}\`).`);
L.push('Owner: Claude Code (session 2bdcad95). Parent schemas under `D:/nova/schemas/` are pinned read-only; nothing here amends them.');
L.push('Rules: see `CONVENTIONS.md`. Every adapter is a **pilot_adapter** (payload meaning differs from the parent where DMV cannot honestly');
L.push('fill a parent-required field); none claims mathematical subset compatibility. Every dropped or weakened parent rule is restored as a');
L.push('named deterministic check run by `tools/belt/post-validate.mjs` (`validateArtifact({stage_id, artifact, context})`).');
L.push('');
L.push('"PASS" from these tools means: adapter schema valid + every compensating check PASS on exact bytes. It is **not** provider');
L.push('acceptance (unverified until the first authorized qualification call), not a belt result, not a qualification result.');
L.push('');
L.push('## Stages');
L.push('');
L.push('| stage_id | prompt | adapter | parent (pinned) | kind | deviations | dropped | checks | fixtures |');
L.push('|---|---|---|---|---|---|---|---|---|');
for (const [sid, st] of Object.entries(stageMap.stages)) {
  const m = manifest.stages?.[sid];
  if (!m) { L.push(`| ${sid} | ${st.prompt_path} | ${st.adapter_schema} | ${st.parent_schema.path} | — | — | — | — | missing |`); continue; }
  const fx = (m.fixtures ?? []).map(f => `${f.kind}:${f.expected_status}`).reduce((a, k) => (a[k] = (a[k] ?? 0) + 1, a), {});
  L.push(`| ${sid} | \`${st.prompt_path}\` | \`${st.adapter_schema}\` \`${(m.adapter?.sha256 ?? '').slice(0, 12)}…\` | \`${st.parent_schema.path}\` \`${st.parent_schema.sha256.slice(0, 12)}…\` | ${m.adapter_kind} | ${m.deviation_count ?? '—'} | ${m.dropped_constraint_count ?? '—'} | ${(m.compensating_checks ?? []).length} | ${Object.entries(fx).map(([k, v]) => `${v}× ${k}`).join(', ')} |`);
}
L.push('');
L.push('## Dropped parent invariants → compensating checks');
L.push('');
L.push('Each row is a parent-schema rule the provider-facing adapter does not carry (strict-mode subset) and the check that restores it.');
L.push('');
L.push('| stage_id | parent pointer | keyword | compensating check |');
L.push('|---|---|---|---|');
for (const r of manifest.dropped_parent_invariants_index ?? []) {
  L.push(`| ${r.stage_id} | \`${r.json_pointer}\` | \`${r.keyword}\` | ${Array.isArray(r.compensating_check) ? r.compensating_check.join(', ') : r.compensating_check} |`);
}
L.push('');
L.push('## Sentinels (pilot_adapter only)');
L.push('');
for (const [sid, m] of Object.entries(manifest.stages ?? {})) {
  const s = m.sentinels ?? [];
  if (s.length) L.push(`- **${sid}**: ${s.map(x => typeof x === 'string' ? `\`${x}\`` : `\`${x.field ?? x.path ?? JSON.stringify(x)}\`${x.value ? ` = \`${x.value}\`` : ''}`).join('; ')}`);
}
L.push('');
L.push('## V1 reference projections (fixtures, never DMV results)');
L.push('');
L.push('The citizenship V1 run (`D:/nova/runs/2026-06-11-citizenship/`) was projected into each adapter where an artifact exists. Raw');
L.push('projections mostly **FAIL** on legitimate V1 defects that the v0.4.0 contract now catches (e.g. " | " separators in card backs,');
L.push('"Here is the official answer" in narration, 17 `needs_review` items, a 60% form overlap without a note, stale 130/128 counts);');
L.push('each mapping records those as `expected_status: FAIL` with the reasons. 05.sessions (TeachingUnit) and 19A.units have **no V1');
L.push('equivalent** → recorded `HOLD`, synthetic fixtures only. Nothing was invented to make V1 pass.');
L.push('');
L.push('## Reproduce');
L.push('');
L.push('```');
L.push('node tools/belt/strict-lint.mjs');
L.push('node tools/belt/run-fixtures.mjs');
L.push('node --test tests/belt/<stage>.test.mjs   # one file at a time on Windows');
L.push('node tools/belt/build-mapping-manifest.mjs --strict');
L.push('node tools/belt/build-receipt.mjs');
L.push('```');
writeFileSync(join(ROOT, 'schemas-strict/README.md'), L.join('\n') + '\n');
console.log('wrote schemas-strict/README.md', sha256File(join(ROOT, 'schemas-strict/README.md')), 'rows', (manifest.dropped_parent_invariants_index ?? []).length);
