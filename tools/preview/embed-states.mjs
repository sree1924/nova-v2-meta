// embed-states.mjs — preview lane (multi-state shell).
// Copies app-preview/data/states.json (the state registry) into
// app-preview/states-embedded.js as window.__STATES_EMBEDDED, the identical
// content fallback for file:// opens (fetch is blocked there). Same pattern
// as embed-audio-manifest.mjs. Validates the shape before writing.
//
// Usage: node tools/preview/embed-states.mjs
// No network, no model calls.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const laneRoot = path.resolve(here, '..', '..');
const src = path.join(laneRoot, 'app-preview', 'data', 'states.json');
const dst = path.join(laneRoot, 'app-preview', 'states-embedded.js');

const states = JSON.parse(fs.readFileSync(src, 'utf8'));
const REQUIRED = ['code', 'name', 'run_id', 'handbook', 'test', 'data_root', 'audio_root', 'audio_manifest', 'status', 'authored_by'];
const STATUSES = new Set(['complete', 'building', 'sme_only']);
const problems = [];
if (!Array.isArray(states) || !states.length) problems.push('states.json must be a non-empty array');
const seen = new Set();
for (const [i, s] of (Array.isArray(states) ? states : []).entries()) {
  for (const k of REQUIRED) if (typeof s[k] !== 'string' || !s[k]) problems.push(`entry ${i}: missing ${k}`);
  if (s.code && !/^[A-Z]{2}$/.test(s.code)) problems.push(`entry ${i}: code must be two capital letters`);
  if (s.code && seen.has(s.code)) problems.push(`entry ${i}: duplicate code ${s.code}`);
  seen.add(s.code);
  if (s.status && !STATUSES.has(s.status)) problems.push(`entry ${i}: status must be one of ${[...STATUSES].join('/')}`);
  if (s.chapters && !Array.isArray(s.chapters)) problems.push(`entry ${i}: chapters must be an array`);
}
if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(2);
}
const out = '// GENERATED by tools/preview/embed-states.mjs — identical content fallback for file:// opens.\n'
  + '// Regenerate after editing app-preview/data/states.json: node tools/preview/embed-states.mjs.\n'
  + 'window.__STATES_EMBEDDED = ' + JSON.stringify(states) + ';\n';
fs.writeFileSync(dst, out);
console.log(`wrote ${path.relative(laneRoot, dst)} (${states.length} state(s), ${out.length} bytes)`);
