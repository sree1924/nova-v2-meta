// embed-audio-manifest.mjs — preview lane (Muse Code).
// Copies app-preview/audio/audio-manifest.json into
// app-preview/audio-manifest-embedded.js as window.__AUDIO_MANIFEST_EMBEDDED,
// the identical-content fallback for file:// opens (same pattern as
// export-content.mjs -> data-real-embedded.js). The learner app tries
// fetch("audio/audio-manifest.json") first and falls back to this copy.
// Read-only w.r.t. the belt: the manifest itself is an input, never edited.
//
// Usage: node tools/preview/embed-audio-manifest.mjs [--manifest <json>] [--out <js>]
// Defaults = Utah (app-preview/audio/audio-manifest.json ->
// app-preview/audio-manifest-embedded.js). Another state in the multi-state
// shell: --manifest app-preview/audio/<xx>/audio-manifest.json
//        --out app-preview/audio/<xx>/audio-manifest-embedded.js
// (paths relative to the lane root; must match the states.json entry).
// No network, no model calls.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const laneRoot = path.resolve(here, '..', '..');
const args = process.argv.slice(2);
const opt = (name, dflt) => {
  const i = args.indexOf(name);
  return i >= 0 && args[i + 1] ? args[i + 1] : dflt;
};
const src = path.resolve(laneRoot, opt('--manifest', 'app-preview/audio/audio-manifest.json'));
const dst = path.resolve(laneRoot, opt('--out', 'app-preview/audio-manifest-embedded.js'));

const raw = fs.readFileSync(src, 'utf8');
const m = JSON.parse(raw);
if (!Array.isArray(m.entries) || !m.totals || !m.think) {
  console.error('audio manifest missing entries/totals/think');
  process.exit(2);
}
const out = '// GENERATED by tools/preview/embed-audio-manifest.mjs — identical content fallback for file:// opens.\n'
  + '// Regenerate after the fleet re-mints: node tools/preview/embed-audio-manifest.mjs.\n'
  + 'window.__AUDIO_MANIFEST_EMBEDDED = ' + JSON.stringify(m) + ';\n';
fs.writeFileSync(dst, out);
console.log(`wrote ${path.relative(laneRoot, dst)} (${m.entries.length} entries, ${out.length} bytes)`);
