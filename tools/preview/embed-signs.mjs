// embed-signs.mjs — preview lane (national road signs package).
// Copies app-preview/data/signs/{signs,by-state,quiz}.json (read-only) into
// app-preview/signs-embedded.js as window.__SIGNS_EMBEDDED, the identical
// content fallback for file:// opens (where fetch is blocked).
//
// Usage: node tools/preview/embed-signs.mjs
// No network, no model calls.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const laneRoot = path.resolve(here, '..', '..');
const signsDir = path.join(laneRoot, 'app-preview', 'data', 'signs');
const dst = path.join(laneRoot, 'app-preview', 'signs-embedded.js');

const signs = JSON.parse(fs.readFileSync(path.join(signsDir, 'signs.json'), 'utf8'));
const byState = JSON.parse(fs.readFileSync(path.join(signsDir, 'by-state.json'), 'utf8'));
const quiz = JSON.parse(fs.readFileSync(path.join(signsDir, 'quiz.json'), 'utf8'));

if (!Array.isArray(signs.signs) || !signs.signs.length) {
  console.error('signs.json must contain a non-empty signs array');
  process.exit(2);
}
if (!byState.states || typeof byState.states !== 'object') {
  console.error('by-state.json must contain a states map');
  process.exit(2);
}
if (!Array.isArray(quiz.items) || !quiz.items.length) {
  console.error('quiz.json must contain a non-empty items array');
  process.exit(2);
}

const payload = { signs, byState, quiz };
const out = '// GENERATED by tools/preview/embed-signs.mjs — identical content fallback for file:// opens.\n'
  + '// Source (read-only): app-preview/data/signs/{signs,by-state,quiz}.json.\n'
  + 'window.__SIGNS_EMBEDDED = ' + JSON.stringify(payload) + ';\n';
fs.writeFileSync(dst, out);
console.log(`wrote ${path.relative(laneRoot, dst)} (${signs.signs.length} signs, ${Object.keys(byState.states).length} states, ${quiz.items.length} quiz items, ${out.length} bytes)`);
